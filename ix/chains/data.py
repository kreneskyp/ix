class GenerateData(LLMChain):
    """Generate a datastructure from a schema passed in from an input.

    This chain supports generate arbitrary datastructures. A JSON schema is passed
    in as an input and the chain generates a datastructure that matches the schema
    using an OpenAI function.

    This pattern allows for the JSON schema to be selected or generated at runtime.
    For example, the schema could be fetched from a database or generated by the
    llm in a prior step.
    """

    input_key: str = "schema"
    """Name of the input that contains a JSON schema."""
    output_key: str = "text"
    """Name of the output that contains the generated datastructure."""

    async def agenerate(
        self,
        input_list: List[Dict[str, Any]],
        run_manager: Optional[AsyncCallbackManagerForChainRun] = None,
    ) -> LLMResult:
        """Generate LLM result from inputs."""
        prompts, stop = await self.aprep_prompts(input_list, run_manager=run_manager)

        # get schema input:
        schema_input = None
        for generation_input in input_list:
            if generation_input["name"] == self.input_key:
                schema_input = generation_input
                break

        if not schema_input:
            raise ValueError(
                f"Could not find input with name {self.input_key} from inputs: {input_list}"
            )

        # generate OpenAI function for the schema and add it to the llm_kwargs
        llm_kwargs = self.llm_kwargs.copy()
        llm_kwargs["functions"] = [
            {
                "name": "generate_data",
                "description": "Generate data structure for user request.",
                "parameters": schema_input,
            }
        ]
        llm_kwargs["function_call"] = {"name": "generate_data"}
        return await self.llm.agenerate_prompt(
            prompts,
            stop,
            callbacks=run_manager.get_child() if run_manager else None,
            **llm_kwargs,
        )
